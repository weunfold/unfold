#!/usr/bin/env node
// Pin the badge icons to one lucide-static release. Reads an extracted
// `npm pack lucide-static@<version>` tree and an extracted feather-icons tree (both outside this
// repo), and writes:
//   src/icons.generated.mjs                      the element lists of the icons the taxonomy uses
//   third_party/lucide-static-<v>/LICENSE        verbatim (ISC; names the Feather-derived portions)
//   third_party/lucide-static-<v>/SOURCE.json    package, version, tarball, integrity, per-icon sha256
//   third_party/feather-icons-<v>/LICENSE        verbatim (MIT, Cole Bemis), with its SOURCE.json
//
//   node tools/pin-icons.mjs <lucide-package-dir> <lucide-integrity> <feather-package-dir> <feather-integrity>
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { KINDS } from '../src/taxonomy.mjs'

const HERE = join(dirname(fileURLToPath(import.meta.url)), '..')
const [lucideDir, lucideIntegrity, featherDir, featherIntegrity] = process.argv.slice(2)
if (!featherIntegrity) throw new Error('usage: pin-icons.mjs <lucide-dir> <lucide-integrity> <feather-dir> <feather-integrity>')
const sha = (b) => createHash('sha256').update(b).digest('hex')
const lucide = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8'))
const feather = JSON.parse(readFileSync(join(featherDir, 'package.json'), 'utf8'))
if (lucide.name !== 'lucide-static' || feather.name !== 'feather-icons') throw new Error('unexpected packages')
const names = [...new Set(Object.values(KINDS).map((k) => k.icon))].sort()
const ICONS = {}
const hashes = {}
for (const name of names) {
  const svg = readFileSync(join(lucideDir, 'icons', `${name}.svg`), 'utf8')
  hashes[name] = sha(svg)
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
  ICONS[name] = [...body.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]*?)\s*\/>/g)].map(([, tag, attrs]) => [tag, Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))])
  if (!ICONS[name].length) throw new Error(`no elements in ${name}.svg`)
}
const lv = lucide.version
const out = join(HERE, 'third_party', `lucide-static-${lv}`)
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'LICENSE'), readFileSync(join(lucideDir, 'LICENSE')))
writeFileSync(join(out, 'SOURCE.json'), `${JSON.stringify({ package: 'lucide-static', version: lv, tarball: `https://registry.npmjs.org/lucide-static/-/lucide-static-${lv}.tgz`, integrity: lucideIntegrity, license: lucide.license, icons: hashes }, null, 2)}\n`)
const fv = feather.version
const fout = join(HERE, 'third_party', `feather-icons-${fv}`)
mkdirSync(fout, { recursive: true })
writeFileSync(join(fout, 'LICENSE'), readFileSync(join(featherDir, 'LICENSE')))
writeFileSync(join(fout, 'SOURCE.json'), `${JSON.stringify({ package: 'feather-icons', version: fv, tarball: `https://registry.npmjs.org/feather-icons/-/feather-icons-${fv}.tgz`, integrity: featherIntegrity, license: feather.license, why: 'Lucide names portions of its icons as Feather (MIT) work; this is that MIT notice' }, null, 2)}\n`)
writeFileSync(join(HERE, 'src/icons.generated.mjs'), `// GENERATED by tools/pin-icons.mjs from lucide-static ${lv} (ISC; portions Feather, MIT).
// Notices: third_party/lucide-static-${lv}/LICENSE and third_party/feather-icons-${fv}/LICENSE.
// Do not edit; re-run the tool against a pinned release instead.
export const ICON_SOURCE = ${JSON.stringify({ package: 'lucide-static', version: lv, integrity: lucideIntegrity, sha256: hashes })}
export const ICONS = ${JSON.stringify(ICONS)}
`)
console.log(`pinned ${names.length} icons from lucide-static ${lv}; feather-icons ${fv} notice`)
